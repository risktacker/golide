#!/usr/bin/env python3
"""Generate the light theme from the dark stylesheets.

The site is designed dark-first with colours written directly in the CSS.
Rather than hand-maintaining a second copy, this script reads every rule that
sets a colour and writes the light equivalent between markers at the end of
the same file:

* neutrals flip lightness (near-black surfaces become paper, white text
  becomes ink) keeping their hue;
* accents (gold, cyan, green...) are darkened enough to read on white;
* white hairlines become ink hairlines at the same opacity; black shadows
  become soft grey shadows.

Run after changing any dark colours:  python3 scripts/generate-light-theme.py
Light mode is active when <html data-theme="light">.
"""

from __future__ import annotations

import colorsys
import re
import sys
from pathlib import Path

import tinycss2

ROOT = Path(__file__).resolve().parents[1]
FILES = [
    ROOT / "app/globals.css",
    *sorted((ROOT / "app").rglob("*.module.css")),
]
START = "/* @light-theme:start (generated by scripts/generate-light-theme.py, do not edit) */"
END = "/* @light-theme:end */"

COLOR = re.compile(r"#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})\b|rgba?\(\s*[\d.]+\s*,\s*[\d.]+\s*,\s*[\d.]+\s*(?:,\s*[\d.%]+\s*)?\)")
NAMED = {"white": (255, 255, 255, 1.0), "black": (0, 0, 0, 1.0), "#fff": (255, 255, 255, 1.0)}
SKIP_PROPS = {"font-family", "src", "content", "mask", "-webkit-mask"}


def parse(token: str):
    if token.startswith("#"):
        h = token[1:]
        if len(h) in (3, 4):
            h = "".join(c * 2 for c in h)
        r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
        a = int(h[6:8], 16) / 255 if len(h) == 8 else 1.0
        return r, g, b, a
    nums = [x.strip() for x in token[token.index("(") + 1:-1].split(",")]
    r, g, b = (float(n) for n in nums[:3])
    a = float(nums[3].rstrip("%")) / (100 if nums[3].endswith("%") else 1) if len(nums) > 3 else 1.0
    return r, g, b, a


def fmt(r, g, b, a):
    r, g, b = (max(0, min(255, round(v))) for v in (r, g, b))
    if a >= 0.999:
        return f"#{r:02x}{g:02x}{b:02x}"
    return f"rgba({r},{g},{b},{round(a, 3)})"


SHADOW_PROPS = ("box-shadow", "text-shadow", "filter", "-webkit-filter")


def to_light(token: str, prop: str = "") -> str:
    r, g, b, a = parse(token)
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    chroma = (max(r, g, b) - min(r, g, b)) / 255
    if a < 0.999 and l > 0.85 and chroma < 0.12:
        # White veils / hairlines on dark become ink veils on light.
        return fmt(18, 20, 26, min(1.0, a * 1.15))
    if a < 0.999 and l < 0.12 and chroma < 0.12:
        if prop in SHADOW_PROPS:
            # Black shadows become softer grey ones.
            return fmt(18, 20, 26, a * 0.35)
        # Dark see-through panels and scrims become see-through paper.
        return fmt(247, 248, 250, a)
    if chroma < 0.16:
        # Neutral: flip lightness, keep a hint of hue.
        nl = 1.0 - l
        nl = 0.955 + (nl - 0.85) * 0.25 if nl > 0.85 else max(0.07, min(0.93, nl))
        nr, ng, nb = colorsys.hls_to_rgb(h, nl, min(s, 0.12))
        return fmt(nr * 255, ng * 255, nb * 255, a)
    # Accent: dark-mode accents are bright; on paper they must be deeper.
    if l > 0.45:
        nl = max(0.28, min(0.44, 1.0 - l * 0.95))
        ns = min(1.0, s * 0.9)
    else:
        nl = min(0.96, 1.0 - l * 0.6)
        ns = s * 0.45
    nr, ng, nb = colorsys.hls_to_rgb(h, nl, ns)
    return fmt(nr * 255, ng * 255, nb * 255, a)


def light_value(value: str, prop: str = "") -> str | None:
    found = False

    def swap(m):
        nonlocal found
        found = True
        return to_light(m.group(0), prop)

    out = COLOR.sub(swap, value)
    for word, rgba in (("white", (255, 255, 255, 1.0)), ("black", (0, 0, 0, 1.0))):
        if re.search(rf"(?<![-\w]){word}(?![-\w])", out):
            out = re.sub(rf"(?<![-\w]){word}(?![-\w])", to_light(fmt(*rgba), prop), out)
            found = True
    return out if found else None


def scope(selector: str, module: bool) -> str:
    prefix = ':global([data-theme="light"])' if module else '[data-theme="light"]'
    parts = []
    for sel in split_selectors(selector):
        sel = sel.strip()
        if not sel:
            continue
        if not module and re.match(r"^(:root|html)\b", sel):
            parts.append(re.sub(r"^(:root|html)", r"\1" + '[data-theme="light"]', sel, count=1))
        elif module and sel.startswith(":global(:root)"):
            parts.append(':global(:root[data-theme="light"])' + sel[len(":global(:root)"):])
        else:
            parts.append(f"{prefix} {sel}")
    return ",".join(parts)


def split_selectors(selector: str):
    depth, cur = 0, ""
    for ch in selector:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            yield cur
            cur = ""
        else:
            cur += ch
    yield cur


def rules(nodes, module: bool, out: list[str]):
    for node in nodes:
        if node.type == "qualified-rule":
            prelude = tinycss2.serialize(node.prelude).strip()
            decls = tinycss2.parse_declaration_list(node.content, skip_whitespace=True, skip_comments=True)
            light = []
            clips = []
            for d in decls:
                if d.type != "declaration":
                    continue
                if d.lower_name in ("background-clip", "-webkit-background-clip", "-webkit-text-fill-color"):
                    clips.append(f"{d.name}:{tinycss2.serialize(d.value).strip()}{'!important' if d.important else ''}")
                if d.lower_name in SKIP_PROPS:
                    continue
                value = tinycss2.serialize(d.value).strip()
                swapped = light_value(value, d.lower_name)
                if swapped is not None and swapped != value:
                    light.append(f"{d.name}:{swapped}{'!important' if d.important else ''}")
            # A "background" shorthand resets clipping (gradient text); restore it.
            if light and clips and any(item.startswith("background:") for item in light):
                light.extend(clips)
            if light:
                out.append(f"{scope(prelude, module)}{{{';'.join(light)}}}")
        elif node.type == "at-rule" and node.lower_at_keyword in ("media", "supports", "container", "layer") and node.content:
            inner: list[str] = []
            rules(tinycss2.parse_rule_list(node.content, skip_whitespace=True, skip_comments=True), module, inner)
            if inner:
                out.append(f"@{node.at_keyword} {tinycss2.serialize(node.prelude).strip()}{{{''.join(inner)}}}")


def generate(path: Path) -> int:
    text = path.read_text(encoding="utf-8")
    base = text.split(START)[0].rstrip() + "\n"
    module = path.name.endswith(".module.css")
    out: list[str] = []
    rules(tinycss2.parse_stylesheet(base, skip_whitespace=True, skip_comments=True), module, out)
    path.write_text(base + "\n" + START + "\n" + "\n".join(out) + "\n" + END + "\n", encoding="utf-8")
    return len(out)


if __name__ == "__main__":
    files = [Path(p) for p in sys.argv[1:]] or FILES
    for f in files:
        print(f"{f.relative_to(ROOT)}: {generate(f)} light rules")
